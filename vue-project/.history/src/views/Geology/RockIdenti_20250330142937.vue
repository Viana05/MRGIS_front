              <!-- 喷出岩——流纹岩 -->
              <div>(3)喷出岩——流纹岩</div>
              <div>
                <p>
                  <strong>肉眼描述：</strong
                  >浅紫色，斑状结构，流纹构造，气孔构造，斑晶成分为石英和透长石。石英为不规则粒状，无色，油脂光泽，贝壳状断口。透长石为柱状，无色透明，玻璃光泽，有解理。基质为隐晶质，浅紫色为主，夹杂有粉红和白色，稍有拉长的气孔和柱状透长石组成的定向排列，斑晶直径1－2
                  mm，约占岩石体积15%。
                </p>
                <p>
                  <strong>镜下描述：</strong
                  >斑状结构，流纹构造，斑晶成分为透长石和石英。基质具霏细结构，局部玻璃质结构，略带黑色不透明微粒，占75%。
                </p>
                <p><strong>岩石定名：</strong>流纹岩</p>
              </div>
            </div>
            <div>6.岩浆岩类的野外鉴定特征</div>
            <div>
              <div>(1)橄榄岩-苦橄岩类</div>
              <div>
                <p>手标本特征：</p>
                <p>
                  <strong>纯橄榄岩：</strong
                  >几乎全由橄榄石组成。橄榄石为浅绿色，粒状，玻璃光泽，没有解理。
                </p>
                <p><strong>橄榄岩：</strong>主要由橄榄石组成，其次为辉石。</p>
                <p><strong>辉石岩：</strong>几乎全由辉石组成。</p>
                <p>
                  <strong>蛇纹石化橄榄岩：</strong
                  >网格状构造，有粒状橄榄石的残核。蛇纹石为橄榄岩蚀变产物。
                </p>
                <p>
                  <strong>苦橄岩：</strong
                  >以橄榄石为主，可出现少量的角闪石、黑云母等。成分相当于橄榄岩。
                </p>
                <p>镜下特征：</p>
                <p><strong>纯橄榄岩：</strong>橄榄石呈白形粒状或他形粒状。</p>
                <p><strong>辉石岩：</strong>斜方辉石和单斜辉石均有。</p>
                <p>
                  <strong>蛇纹石化橄榄岩：</strong
                  >蛇纹石化从岩石裂隙或橄榄石粒间开始，蚀变不彻底，仍残留有小颗粒橄榄石（残留结构），蛇纹石化过程中析出铁质，生成磁铁矿小微粒，呈不规则地分布在蛇纹石中。
                </p>
              </div>
              <div>(2)辉长岩一玄武岩类</div>
              <div>
                <p>鉴定特征：</p>
                <p>
                  <strong>辉长岩：</strong
                  >主要矿物由基佳斜长石和单斜辉石（透辉石、普通辉石、异剥辉石）组成。次要矿物有橄榄石、斜方辉石，有时有角闪石和黑云母，甚至钾长石和石英。副矿物有磁铁矿、钛铁矿、磷灰石。暗色矿物和浅色矿物含量近于1：1，色率为35－65。岩石颜色深，常呈黑色、灰色等。辉长结构，块状构造，有时呈条带状构造。辉长岩可形成独立的岩体，也可与橄榄岩构成杂岩体。
                  主要由辉石和基性科长石组成，粗一中粒辉长结构。
                </p>
                <p><strong>斜长岩：</strong>几乎全由斜长石组成。</p>
                <p>
                  <strong>辉绿岩：</strong
                  >为浅成侵人岩。矿物成分与辉长岩相似，即主要由基性斜长石和单斜辉石组成。未经蚀变的辉绿岩，颜色多为深灰或黑色，风化后呈浅绿或绿灰色。具辉绿结构（即白色的细长条斜长石搭成三角架，其间充填粒状的辉石）。辉绿岩易于蚀变，其蚀变情况大致与辉长岩相同。具有斑状结构的辉绿岩，称为辉绿玢岩。斑晶为基性斜长石和暗色矿物。
                </p>
                <p>
                  <strong>辉绿玢岩：</strong
                  >具斑状结构的辉绿岩，斑晶为斜长石和暗色矿物。
                </p>
                <p>
                  <strong>细晶辉长岩：</strong
                  >成分与辉长岩相同，只是具细粒结构而不具其它结构为特征。
                </p>
                <p>
                  <strong>橄榄玄武岩：</strong
                  >能见到橄榄石斑晶，常见橄榄石的蚀变产物——伊丁石。基质为隐晶质。
                </p>
                <p>
                  <strong>玄武岩：</strong
                  >肉眼观察为隐晶质，颜色多为黑色，黑绿色，有时为暗紫色。粗玄结构或间隐结构。有时具斑状结构。块状构造、气孔状构造。后层玄武岩中常见柱状节理。矿物成分以辉石和基性斜长石为主，这是与安山岩的主要区别。
                </p>
                <p>
                  <strong>杏仁状玄武岩：</strong>气孔中充填有白色的沸石等矿物。
                </p>
              </div>
              <div>(3)闪长岩一安山岩类</div>
              <div>
                <p>
                  此类岩石常见有闪长岩、石英闪长岩、闪长玢岩、细晶闪长岩、安山岩、英安岩。
                </p>
                <p>鉴定特征：</p>
                <p>
                  <strong>闪长岩：</strong
                  >主要由中性斜长石和角闪石（或黑云母）组成，斜长石含量大于角闪石含量，并含有少量的黑云母、辉石、正长石和石英（＜5%）。暗色矿物含量为1／3
                  左右。颜色浅灰至灰绿色。自形或半自形粒状结构，有时具似斑状结构。
                </p>
                <p>
                  <strong>石英闪长岩：</strong
                  >闪长岩中含有5％－20％的石英，称石英闪长岩。组成石英闪长岩的矿物仍以中性斜长石和角闪石为主。暗色矿物含量在15％左右。除角闪石外，还有黑云母、辉石。颜色浅灰，半自形粒状结构，块状构造。
                </p>
                <p>
                  <strong>闪长玢岩：</strong
                  >矿物成分与闪长岩相同，为闪长岩体边部产物或浅成侵人岩石。暗灰至暗绿色。斑状结构，斑晶为中性斜长石和角闪石或黑云母，基质为细粒或隐晶质物质。
                </p>
                <p>
                  <strong>细晶闪长岩：</strong>成分与闪长玢岩相同，具细晶结构。
                </p>
                <p>
                  <strong>安山岩：</strong
                  >主要由中性斜长石和角闪石组成。肉眼观察呈浅灰、深灰、红褐，以至黑色。蚀变后色调变成绿色。常具斑状结构，斑晶为宽板状中长石（斜长石）、辉石、角闪石、黑云母等，基质为隐晶质或玻基交织结构。斜长石有环带结构，角闪石和黑云母有暗化边现象，块状或气孔构造等。注意角闪石、黑云母斑晶具暗化边，基质为安山结构或交织结构。
                </p>
              </div>
              <div>(4)正长岩一粗面岩类</div>
              <div>
                <p>主要岩石类型为正长岩、二长岩、正长斑岩、粗面岩。</p>
                <p>手标本特征：</p>
                <p>
                  <strong>正长岩：</strong
                  >肉红色或浅土黄色的板状正长石为主，还有少量的斜长石和黑云母。
                </p>
                <p><strong>二长岩：</strong>由钾长石、斜长石大致各半组成。</p>
                <p><strong>正长斑岩：</strong>斑状结构，成分与正长岩相同。</p>
                <p>
                  <strong>粗面岩：</strong
                  >断口粗糙，斑状结构。透长石和斜长石组成斑晶，基质为隐晶质。
                </p>
                <p>镜下特征：</p>
                <p><strong>正长岩：</strong>以正长石为主，暗色矿物为黑云母。</p>
                <p>
                  <strong>粗面岩：</strong
                  >斑状结构，斑晶以透长石为主，并有少量黑云母、斜长石，基质为粗面结构（即大量碱性长石的柱状晶体成大致平行排列）或正斑结构（即石英或玻璃质基质中发了有许多正方形和长方形碱性长石微晶，是粗面岩、正长斑岩等斑状岩石中基质的结构）。
                </p>
              </div>
              <div>（5）花岗闪长岩一流纹英安岩类和花岗岩一流纹岩类</div>
              <div>
                <p>
                  此类岩石的主要类型有花岗岩、花岗闪长岩、花岗斑岩、花岗闪长斑岩、流纹英安岩、流纹岩、松脂岩、珍珠岩、黑曜岩。
                </p>
                <p>鉴定特征：</p>
                <p>
                  <strong>花岗闪长岩：</strong
                  >为花岗岩向闪长岩的过渡岩石，主要矿物有石英，约占20％。酸性或中性斜长石占全部长石的65％－90%，碱性长石占全部长石的35％以下，即斜长石与钾长石之比为2∶1。暗色矿物约15%，以角闪石为主，还有黑云母和辉石。副矿物有榍石、磷灰石、磁铁矿、锆石、褐帘石、独居石等。含斜长石和暗色矿物比花岗岩多一些，因而颜色稍深，呈灰绿色或暗灰色。
                </p>
                <p>
                  <strong>花岗斑岩：</strong
                  >是成分相当于花岗岩的浅成岩。全晶质、斑状结构。斑晶主要是碱性长石和石英，有时也有黑云母、角闪石等。基质成分与斑晶相同，隐晶至微晶结构。致密块状。
                </p>
                <p>
                  <strong>花岗闪长斑岩：</strong
                  >是矿物成分相当于花岗闪长岩的浅成岩。全晶质、斑状结构。斑晶以斜长石为主，但有少量的铁镁矿物、钾长石和石英作斑晶。基质为细粒石英、斜长石和碱性长石。
                </p>
                <p>
                  <strong>花岗岩：</strong
                  >中一细粒花岗结构，块状构造。石英占30％左右，长石占60％左右，暗色矿物（黑云母）＜10％。钾长石＞斜长石。
                </p>
                <p><strong>流纹岩：</strong>具流纹构造。</p>
                <p>
                  <strong>流纹斑岩：</strong
                  >具有长石和石英斑晶的流纹岩，斑晶含量＞30％。
                </p>
                <p>
                  <strong>石英斑岩：</strong
                  >以石英为斑晶的流纹岩。但也有浅成的石英斑岩。
                </p>
                <p>
                  <strong>流纹英安岩：</strong
                  >成分与花岗闪长岩相同，斑晶为斜长石、角闪石、黑云母，可有少量石英和钾长石，基质为隐晶质或玻璃质。
                </p>
                <p>
                  <strong>黑曜岩：</strong
                  >黑色，灰黑色玻璃岩石。玻璃光泽，贝壳状断口，有时含少量透长石斑晶。
                </p>
                <p>
                  <strong>珍珠岩：</strong
                  >具珍珠裂缝的玻璃质岩石（珍珠构造），有时含有各色的珍珠球。
                </p>
                <p><strong>松脂岩：</strong>树脂光泽或油脂光泽。</p>
              </div>
              <div>（6）霞石正长岩一响岩类</div>
              <div>
                <p>
                  此类岩石的主要类型有霞石正长岩、霞石正长斑岩、白榴石响岩。
                </p>
                <p>手标本特征：</p>
                <p>
                  <strong>霞石正长岩：</strong
                  >由长板状的正长石组成，次为霞石（深肉红色，粒状，油脂光泽，没有解理）和碱性暗色矿物（碱性辉石和碱性角闪石）。
                </p>
                <p>
                  <strong>霞石正长斑岩：</strong
                  >成分与霞石正长岩相同。正长石和霞石为斑晶。
                </p>
                <p>
                  <strong>响岩：</strong
                  >白榴石、透长石为斑晶，基质与斑晶成分相同，微晶结构。白榴石不稳定，可被正长石、霞石、方沸石代替，此种岩石称为假白榴石响岩。
                </p>
              </div>
              <div>(7)煌斑岩类、伟晶岩类和细晶岩类</div>
              <div>
                <p>
                  此类岩石的主要类型有云煌岩、金伯利岩、花岗细晶岩，花岗伟晶岩、闪斜煌斑岩。
                </p>
                <p>鉴定特征：</p>
                <p>
                  <strong>云煌岩：</strong
                  >主要成分为黑云母，其次为正长石。黑云母多呈褐色，略带红色，有时为绿色，假六方片状、自形晶。有些云煌岩含金云母。碱性长石晶形完整，但易于分解而变得浑浊。斑状结构，斑晶多为黑云母，基质主要由钾长石、黑云母组成。云煌岩多分布在花岗岩、花岗闪长岩和正长岩体内部。
                  闪正煌岩：由富钾碱性长石、普通角闪石和普通辉石组成，并含少量斜长石、黑云母、石英、磷灰石、磁铁矿等。斑状结构。
                </p>
                <p>
                  <strong>云斜煌岩：</strong
                  >由斜长石、黑云母、普通辉石组成。有时呈斑状结构。
                </p>
                <p>
                  <strong>闪斜煌岩：</strong
                  >由普通角闪石和斜长石组成，角闪石呈斑晶，基质亦为粒状自形晶。含量在40％以上，此外可含有透辉石、橄揽石（假像）、黑云母、正长石、石英、磷灰石。
                </p>
                <p>
                  <strong>金伯利岩：</strong
                  >主要由橄榄石、铬透辉石、金云母组成，具角砾构造。
                </p>
                <p>
                  <strong>花岗细晶岩：</strong
                  >细晶结构，主要由石英、钾长石、斜长石组成、花岗伟晶岩：伟晶结构，晶体颗粒粗大，有时呈文象结构。
                </p>
                <p>
                  <strong>闪斜煌斑岩：</strong
                  >主要矿物为角闪石．其次为斜长石：斑状结构；斑晶为角闪石．基质由斜长石及角闪石组成。
                </p>
                <p>镜下特征：</p>
                <p>
                  <strong>云煌岩：</strong
                  >黑云母自形程度好，有时可见斜长石的环带。
                </p>
                <p><strong>闪斜煌斑岩：</strong>角闪石的自形程度很好。</p>
                <p>
                  <strong>金伯利岩：</strong
                  >角砾状构造，斑状结构，角砾多为早期熔岩，斑晶为橄榄石，但已蛇纹石化，熔蚀后成圆粒状。岩石碳酸盐化、金云母化、蛇纹石化、绿泥石化强烈。
                </p>
              </div>
            </div>
