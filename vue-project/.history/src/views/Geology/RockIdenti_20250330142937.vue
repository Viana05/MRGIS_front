          <el-collapse-item title="02沉积岩" name="5">
            <div>1.砾岩、角砾岩、砂岩</div>
            <div>
              <p>
                常见岩石类型有砾岩、角砾岩、石英砂岩、长石砂岩、岩屑杂砂岩、铁质砂岩、海绿石砂岩、细粒砂岩、中粒砂岩、粗粒砂岩。
              </p>
              <div>（1）鉴定方法和步骤</div>
              <div>
                <div>
                  <div>鉴别确定岩石中的碎屑成分并估计其含量。</div>
                  <p>
                    实际测量（薄片中）和估测（手标本上）碎屑颗粒的粒径（最大、最小和一般的）。（也可利用粒度管或粒度盘以及较标准的标本进行对比）。并确定岩石的分选程度。
                  </p>
                  <div>鉴别碎屑颗粒的磨圆度。</div>
                  <div>鉴别填隙物的成分。</div>
                  <p>
                    <strong>硅质胶结物：</strong
                    >白色、致密状、硬度大于小刀、加HCl不起泡。
                  </p>
                  <p><strong>铁质胶结物：</strong>岩石往往呈紫红色。</p>
                  <p>
                    <strong>碳酸盐质胶结物：</strong>浅灰一浅绿色、加HCl起泡。
                  </p>
                  <p>
                    <strong>海绿石胶结物：</strong
                    >暗绿色，风化后使岩石带绿色斑痕。
                  </p>
                  <p>
                    <strong>泥质杂基：</strong
                    >灰色、褐色、硬度小、岩石易破碎松散、加HCl不起泡。
                  </p>
                </div>
              </div>
              <div>（2）描述实例</div>
              <div>
                <div>I.砾岩</div>
                <p>
                  灰色、砾状结构、胶结紧密、标本呈块状构造。其中砾石占70%，填隙物占30%。砾石大小不一，粒径一般在2-20mm，以2－10mm
                  为主。砾石呈圆状及次圆状，少数次棱角状，断面多呈椭圆及长条形。砾石以石灰岩和白云岩为主，还有少量喷出岩和硅质岩。填隙物浅灰绿色，多为与砾石成分相同的砂及粉砂、砂及粉砂间有钙质、泥质等填隙物。属基底式胶结类型。
                </p>
                <div>紫褐色中粒铁质砂岩</div>
                <p>
                  暗紫褐色、颜色分布不均匀。中粒砂状结构，标本呈块状构造。碎屑含量占整个岩石85%左右，胶结物约占15%。砂粒几乎都是石英，粒径0.15-1
                  mm
                  左右，分选性好，大小比较一致。胶结物主要为氧化铁，分布不均匀，局部聚集成团块。岩石为颗粒支撑，呈孔隙式胶结。
                </p>
              </div>
            </div>
            <div>2.粉砂岩、泥质岩</div>
            <div>
              <p>
                此类岩石的主要类型有细粉砂岩、粗粉砂岩、粘土、泥岩、含粉砂泥岩、砂质页岩、铁质页岩、钙质页岩、黑色页岩、碳质页岩、油页岩、硅质页岩。
              </p>
              <div>(1)鉴定方法与步骤</div>
              <div>
                <p>粉砂岩的观察方法与砂岩基本相同。</p>
                <p>
                  泥质岩因矿物颗位非常细小，肉眼无法鉴定，因而要注意其颜色及各种物理性质的观察。
                </p>
                <p>
                  要注意观察泥页岩的断口和手触摸时的感觉，据此来判断其结构类型以及与粉砂岩相区别。
                </p>
                <p>
                  正确区分层理和页理，利用颜色、条痕以及加酸起泡与否等区别各种不同类型的页岩。
                </p>
              </div>
              <div>(2)描述实例</div>
              <div>
                <div>I.含粉砂泥岩</div>
                <p>
                  浅灰色。含粉砂泥质结构，块状均造。断口不太平滑，手摸之略有粗糙感。在水中不易泡软，加盐酸不起泡。由此推断主要由粘土矿物组成，含少量粉砂。
                </p>
                <div>II.红色页岩</div>
                <p>
                  砖红色。泥质结构，页理构造。由于岩石受到轻微变质，使其页理不甚明显。断口呈贝壳状。岩石主要由铁质及粘土矿物组成。
                </p>
              </div>
              <div></div>
            </div>
            <div>3.火山碎屑岩类</div>
            <div>
              <p>
                火山碎屑岩在我国主要形成于中生代，在辽东、辽西和大兴安岭地区分布较广。此类岩石的主要类型有角砾熔岩、熔结凝灰岩（或熔结角砾岩）、火山角砾岩、晶屑凝灰岩、玻屑凝灰岩、层凝灰岩、凝灰（质）砂岩和凝灰（质）页岩。野外最常见的火山碎屑岩有：火山角砾岩和凝灰岩。
              </p>
              <p>
                <strong>火山角砾岩：</strong>由50％以上粒度在64－2mm
                的火山碎屑物组成，具火山角砾结构，斑杂构造。火山角砾棱角明显，分选差，粒度变化大。火山角砾岩一般多分布在火山通道附近，也可在离火山口较远的地方堆积，分布范围较集块岩广泛一些。
              </p>
              <p>
                <strong>凝灰岩：</strong>由70％以上粒度﹤2 mm
                的火山碎屑物组成，具典型的凝灰结构，块状构造。颜色浅而多变，多孔疏松，有粗糙感，次生变化显著。由于粒度细小，常堆积在距火山口较远的地方。是分布最广的一种火山碎屑岩。
              </p>
              <div>（1）观察方法与步骤</div>
              <div>
                <p>
                  观察手标本时要注意区分沉积角砾和火山角砾。火山角砾多为火山岩岩屑、呈棱角状，颜色常为紫红色、灰绿色等，常具斑状结构。
                </p>
                <p>
                  凝灰岩的外貌很象细砂岩、粉砂岩，区别在于颜色较特殊，常为紫红、灰绿色等，有时颜色分布很不均匀。凝灰岩中晶屑多呈棱角状，破碎及熔蚀现象明显，晶面常有较多的裂纹。
                </p>
                <p>
                  凝灰岩与火山熔岩也很相似，但凝灰岩具火山碎屑结构，表面粗糙、粘舌。
                </p>
              </div>
              <div>(2)描述实例</div>
              <div>
                <div>I.火山角砾岩（山西临县）</div>
                <p>
                  褐红一紫红色。火山角砾结构、块状构造。岩石中火山碎屑占90％以上，其中以粒径在10－2mm
                  的熔岩角砾为主（约占75％），此外含少量长石和石英晶屑和玻屑。火山角砾外形不规则，呈尖棱角状。火山角砾为褐红色细小的凝灰质胶结。岩石次生变化不明显。
                </p>
                <div>II.流纹质晶屑玻屑凝灰岩（河北）</div>
                <p>
                  手标本观察：白至灰白色。凝灰结构，块状构造。主要成分为极细小的火山凝灰，石英及长石晶屑约占7％左右。岩石具粗糙感，有粘舌现象。
                </p>
                <p>
                  薄片观察：主要成分为玻屑，呈楔状，局部已脱玻化变成石英、长石的微晶集合体。在玻屑中星散分布有酸性斜长石及少量透长石和石英的晶屑。长石和石英晶屑边缘有熔蚀现象。
                </p>
              </div>
            </div>
            <div>4.碳酸盐岩</div>
            <div>
              <div>1)石灰岩</div>
              <div>
                <p>
                  此类岩石的主要类型：砾屑（竹叶状）灰岩、亮晶砂屑灰岩、亮晶（或泥晶）鲡粒灰岩、泥品生物屑灰岩、亮晶生物屑灰岩、泥晶灰岩、结晶灰岩、礁灰岩。
                </p>
                <div>I．方法与步骤</div>
                <p>
                  （1）利用显微放像设备或显微投影仪，认识和掌握颗粒的各种类型以及泥晶和亮晶的特征及区别。
                </p>
                <p>
                  （2）用水着湿岩石标本的新鲜面，用放大镜观察各种结构组分并进行描述。
                </p>
                <div>II．描述实例</div>
                <p>（1）砾屑灰岩（竹叶状灰岩）</p>
                <p>颜色：灰绿色略带灰红色、颜色分布不均匀。</p>
                <p>矿物成分：几乎全由方解石组成，含微量的铁质。</p>
                <p>
                  结构组分：颗粒：主要为砾屑，圆度好，断面呈长椭圆形，似竹叶状，大小不一，表面被氧化铁包围。砾石成分为泥晶灰岩。还有少量砂屑，其成分也是泥晶灰岩，充填于砾屑之间。填隙物：主要为泥晶基质，均已不同程度地重结晶。
                </p>
                <p>结构：砾屑结构；颗粒支撑，为孔隙式胶结。</p>
                <p>岩石名称：泥晶砾屑灰岩。</p>
                <p>（2）鲕粒灰岩</p>
                <p>颜色：暗紫红色。</p>
                <p>矿物成分：几乎全由方解石组成。</p>
                <p>
                  结构组分：颗粒：主要为鲕粒，一般呈球形，少数椭圆形，大小为1—2mm，
                  有同心层圈），含有铁质，因而成暗红色。鲕粒约占岩石60％。还有＜5%的生物碎屑。填隙物：主要为灰白色，但较浑浊的泥晶方解石，与颗粒界限不清晰，约占岩石的20％－25％；有少量灰白色、较干净明亮的方解石，约占岩石10%。
                </p>
                <p>结构：鲕粒结构；基质支撑，为基底式胶结，颗粒互相不接触。</p>
                <p>构造：块状构造。</p>
                <p>岩石名称：亮晶一泥晶缅拉灰岩</p>
              </div>
              <div>2)白云岩、泥灰岩、硅质灰岩及硅质岩</div>
              <div>
                <p>
                  此类岩石的主要类型：碎屑白云岩、细晶白云岩、中一粗晶白云岩、泥晶白云岩、白云质灰岩、泥灰岩、硅质灰岩、硅藻土、燧石岩、碧玉岩。
                </p>
                <div>I.鉴定方法和步骤</div>
                <p>同石灰岩</p>
                <div>II.描述实例</div>
                <p>（1）泥晶白云岩</p>
                <p>
                  暗灰色。隐晶结构，手标本呈块状构造。岩石致密，断口呈贝壳状，加盐酸微弱起泡。岩石由泥晶白云岩组成。
                </p>
                <p>（2）硅质条带石灰岩</p>
                <p>
                  灰色。隐晶一粉晶结构，条带状构造。岩石由浅灰的粉晶石灰岩（约占岩石70％）和暗灰色的硅质条带（约占岩石30％）组成。石灰岩由粉晶方解石组成，加盐酸剧烈起泡，断口略粗糙不平。硅质条带由燧石组成，致密、硬度大于小刀。
                </p>
              </div>
            </div>
