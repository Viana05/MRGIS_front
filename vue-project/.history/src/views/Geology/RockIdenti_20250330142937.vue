              沉积岩是在岩石循环过程中产生的，三种组成地球岩石圈的主要岩石之一。沉积岩是在地壳发展演化过程中，在地表或接近地表的常温常压条件下，任何先成岩遭受风化剥蚀作用的破坏产物，以及生物作用与火山作用的产物，在原地或经过外力的搬运，所形成的沉积层，又经成岩作用而成的岩石。
            </p>
            <p>沉积岩根据其形成特征，可分为三种基本类型。</p>
            <p>
